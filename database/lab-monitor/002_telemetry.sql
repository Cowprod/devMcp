-- Apply only to a separately provisioned telemetry database.
-- UTC timestamps; immutable samples; no cross-database foreign keys.
CREATE TABLE IF NOT EXISTS T_METRICSAMPLE (
 MTS_N_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 MTS_N_EQU_ID INT NOT NULL,
 MTS_N_MTT_ID INT NOT NULL,
 MTS_CH_SERIES VARCHAR(128) NOT NULL DEFAULT '',
 MTS_DT_SAMPLE DATETIME(6) NOT NULL,
 MTS_N_VALUE DOUBLE NOT NULL,
 UNIQUE KEY (MTS_N_EQU_ID,MTS_N_MTT_ID,MTS_CH_SERIES,MTS_DT_SAMPLE),
 KEY (MTS_DT_SAMPLE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS T_METRICCURRENT (
 MTC_N_EQU_ID INT NOT NULL,
 MTC_N_MTT_ID INT NOT NULL,
 MTC_CH_SERIES VARCHAR(128) NOT NULL DEFAULT '',
 MTC_DT_SAMPLE DATETIME(6) NOT NULL,
 MTC_N_VALUE DOUBLE NOT NULL,
 PRIMARY KEY (MTC_N_EQU_ID,MTC_N_MTT_ID,MTC_CH_SERIES)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS T_METRICROLLUP (
 MTR_N_EQU_ID INT NOT NULL,
 MTR_N_MTT_ID INT NOT NULL,
 MTR_CH_SERIES VARCHAR(128) NOT NULL DEFAULT '',
 MTR_N_RESOLUTION INT NOT NULL,
 MTR_DT_BUCKET DATETIME(6) NOT NULL,
 MTR_N_MIN DOUBLE NOT NULL,
 MTR_N_MAX DOUBLE NOT NULL,
 MTR_N_SUM DOUBLE NOT NULL,
 MTR_N_COUNT BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY (MTR_N_EQU_ID,MTR_N_MTT_ID,MTR_CH_SERIES,MTR_N_RESOLUTION,MTR_DT_BUCKET),
 KEY (MTR_N_RESOLUTION,MTR_DT_BUCKET)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS T_EVENT (
 EVT_N_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 EVT_N_EQU_ID INT NULL,
 EVT_CH_TYPE VARCHAR(64) NOT NULL,
 EVT_CH_SOURCE VARCHAR(128) NOT NULL,
 EVT_CH_EXTERNALID VARCHAR(128) NULL,
 EVT_DT_EVENT DATETIME(6) NOT NULL,
 EVT_CH_DETAILS TEXT NULL,
 UNIQUE KEY (EVT_CH_SOURCE,EVT_CH_EXTERNALID),
 KEY (EVT_N_EQU_ID,EVT_DT_EVENT),
 KEY (EVT_DT_EVENT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS T_ALERT (
 ALT_N_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ALT_N_ALR_ID INT NOT NULL,
 ALT_N_EQU_ID INT NOT NULL,
 ALT_CH_SERIES VARCHAR(128) NOT NULL DEFAULT '',
 ALT_CH_SEVERITY VARCHAR(32) NOT NULL,
 ALT_DT_OPEN DATETIME(6) NOT NULL,
 ALT_DT_CLOSE DATETIME(6) NULL,
 ALT_CH_DETAILS TEXT NULL,
 ALT_BL_OPEN TINYINT GENERATED ALWAYS AS (CASE WHEN ALT_DT_CLOSE IS NULL THEN 1 ELSE NULL END) STORED,
 UNIQUE KEY (ALT_N_ALR_ID,ALT_N_EQU_ID,ALT_CH_SERIES,ALT_BL_OPEN),
 KEY (ALT_DT_OPEN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS T_NOTIFICATIONDELIVERY (
 NDL_N_ID BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 NDL_N_ALT_ID BIGINT UNSIGNED NOT NULL,
 NDL_N_NCH_ID INT NOT NULL,
 NDL_CH_TRANSITION VARCHAR(32) NOT NULL,
 NDL_CH_STATUS VARCHAR(32) NOT NULL,
 NDL_N_ATTEMPTS INT NOT NULL DEFAULT 0,
 NDL_DT_CREATION DATETIME(6) NOT NULL,
 NDL_DT_NEXTATTEMPT DATETIME(6) NULL,
 NDL_DT_SENT DATETIME(6) NULL,
 NDL_CH_ERROR TEXT NULL,
 UNIQUE KEY (NDL_N_ALT_ID,NDL_N_NCH_ID,NDL_CH_TRANSITION),
 KEY (NDL_CH_STATUS,NDL_DT_NEXTATTEMPT),
 FOREIGN KEY (NDL_N_ALT_ID) REFERENCES T_ALERT(ALT_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
