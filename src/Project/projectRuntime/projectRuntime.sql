SELECT PRT_CH_PROJECT AS project_id, RTY_CH_CODE AS runtime_type, PRT_CH_DESIREDSTATE AS desired_state,
       PRT_CH_ENTRYPOINT AS entrypoint, PRT_CH_DOCUMENTROOT AS document_root,
       PRT_CH_HEALTHPATH AS health_path, PRT_N_REVISION AS revision
FROM T_PROJECTRUNTIME
JOIN T_RUNTIMETYPE ON RTY_N_ID = PRT_N_RUNTIMETYPE AND RTY_DT_SUPPRESSION IS NULL
WHERE PRT_DT_SUPPRESSION IS NULL
ORDER BY PRT_CH_PROJECT
