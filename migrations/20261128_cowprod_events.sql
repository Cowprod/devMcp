CREATE TABLE IF NOT EXISTS T_JOBEVENT (
    JEV_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    JEV_N_MID BIGINT UNSIGNED NULL,
    JEV_CH_JOB_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    JEV_CH_EVENT_TYPE VARCHAR(64) NOT NULL,
    JEV_CH_DETAILS_JSON JSON NULL,
    JEV_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    JEV_CH_CREATION VARCHAR(191) NULL DEFAULT 'service:devmcp-scheduler',
    JEV_DT_SUPPRESSION DATETIME(6) NULL,
    JEV_CH_SUPPRESSION VARCHAR(191) NULL,
    KEY JEV_I_JOB (JEV_CH_JOB_ID,JEV_N_ID),
    CONSTRAINT JEV_F_PARENT FOREIGN KEY (JEV_N_MID) REFERENCES T_JOBEVENT (JEV_N_ID),
    CONSTRAINT JEV_F_JOB FOREIGN KEY (JEV_CH_JOB_ID) REFERENCES dm_job(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_AUDITEVENT (
    AUD_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    AUD_N_MID BIGINT UNSIGNED NULL,
    AUD_CH_ACTOR VARCHAR(128) NOT NULL,
    AUD_CH_EVENT_TYPE VARCHAR(64) NOT NULL,
    AUD_CH_OBJECT_TYPE VARCHAR(64) NOT NULL,
    AUD_CH_OBJECT_ID VARCHAR(128) NOT NULL,
    AUD_CH_OUTCOME VARCHAR(32) NOT NULL,
    AUD_CH_DETAILS_JSON JSON NULL,
    AUD_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AUD_CH_CREATION VARCHAR(191) GENERATED ALWAYS AS (AUD_CH_ACTOR) VIRTUAL,
    AUD_DT_SUPPRESSION DATETIME(6) NULL,
    AUD_CH_SUPPRESSION VARCHAR(191) NULL,
    KEY AUD_I_CREATED (AUD_DT_CREATION),
    KEY AUD_I_OBJECT (AUD_CH_OBJECT_TYPE,AUD_CH_OBJECT_ID),
    CONSTRAINT AUD_F_PARENT FOREIGN KEY (AUD_N_MID) REFERENCES T_AUDITEVENT (AUD_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
