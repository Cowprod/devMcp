CREATE TABLE IF NOT EXISTS T_ACTIONTEMPLATE (
    ACT_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ACT_N_MID BIGINT UNSIGNED NULL,
    ACT_CH_ID VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ACT_N_REVISION INT UNSIGNED NOT NULL,
    ACT_CH_DESCRIPTION VARCHAR(255) NOT NULL,
    ACT_CH_RISK ENUM('read','write','hardware') NOT NULL DEFAULT 'read',
    ACT_CH_DEFINITION_SHA256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ACT_DT_CREATION DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
    ACT_CH_CREATION VARCHAR(191) NULL,
    ACT_DT_SUPPRESSION DATETIME(6) NULL,
    ACT_CH_SUPPRESSION VARCHAR(191) NULL,
    ACT_CH_MERE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN ACT_N_MID IS NULL THEN ACT_CH_ID END) STORED,
    ACT_N_REVISIONMERE INT UNSIGNED
        GENERATED ALWAYS AS (CASE WHEN ACT_N_MID IS NULL THEN ACT_N_REVISION END) STORED,
    UNIQUE KEY ACT_U_MERE (ACT_CH_MERE, ACT_N_REVISIONMERE),
    CONSTRAINT ACT_F_PARENT FOREIGN KEY (ACT_N_MID) REFERENCES T_ACTIONTEMPLATE (ACT_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_POLICYREVISION (
    POL_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    POL_N_MID BIGINT UNSIGNED NULL,
    POL_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    POL_CH_DEPLOYMENT_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    POL_N_REVISION_NUMBER INT UNSIGNED NOT NULL,
    POL_CH_POLICY_SHA256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    POL_DT_APPROVED_AT DATETIME(6) NOT NULL,
    POL_DT_CREATION DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
    POL_CH_CREATION VARCHAR(191) NULL,
    POL_DT_SUPPRESSION DATETIME(6) NULL,
    POL_CH_SUPPRESSION VARCHAR(191) NULL,
    POL_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN POL_N_MID IS NULL THEN RTRIM(POL_CH_ID) END) STORED,
    POL_CH_DEPLOYMENTMERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN POL_N_MID IS NULL THEN RTRIM(POL_CH_DEPLOYMENT_ID) END) VIRTUAL,
    POL_N_REVISIONMERE INT UNSIGNED
        GENERATED ALWAYS AS (CASE WHEN POL_N_MID IS NULL THEN POL_N_REVISION_NUMBER END) VIRTUAL,
    UNIQUE KEY POL_U_MERE (POL_CH_MERE),
    UNIQUE KEY POL_U_REVISION (POL_CH_DEPLOYMENTMERE, POL_N_REVISIONMERE),
    KEY POL_I_APPROVAL (POL_CH_DEPLOYMENT_ID, POL_DT_APPROVED_AT, POL_N_REVISION_NUMBER),
    CONSTRAINT POL_F_PARENT FOREIGN KEY (POL_N_MID) REFERENCES T_POLICYREVISION (POL_N_ID),
    CONSTRAINT POL_F_DEPLOYMENT FOREIGN KEY (POL_CH_DEPLOYMENT_ID) REFERENCES T_DEPLOYMENT (DEP_CH_MERE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

