CREATE TABLE IF NOT EXISTS T_JOB (
    JOB_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    JOB_N_MID BIGINT UNSIGNED NULL,
    JOB_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    JOB_CH_DEPLOYMENT_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    JOB_CH_ACTION_ID VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    JOB_N_ACTION_REVISION INT UNSIGNED NOT NULL,
    JOB_CH_ARGUMENTS_JSON JSON NOT NULL,
    JOB_CH_STATUS ENUM('queued','leased','running','succeeded','failed','cancelled','timed_out','expired','uncertain') NOT NULL DEFAULT 'queued',
    JOB_CH_IDEMPOTENCY_KEY VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    JOB_DT_EXPIRES_AT DATETIME(6) NOT NULL,
    JOB_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    JOB_CH_CREATION VARCHAR(191) NULL DEFAULT 'service:devmcp-scheduler',
    JOB_DT_UPDATED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    JOB_CH_POLICY_REVISION_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    JOB_DT_SUPPRESSION DATETIME(6) NULL,
    JOB_CH_SUPPRESSION VARCHAR(191) NULL,
    JOB_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN JOB_N_MID IS NULL THEN RTRIM(JOB_CH_ID) END) STORED,
    JOB_CH_DEPLOYMENTMERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN JOB_N_MID IS NULL THEN RTRIM(JOB_CH_DEPLOYMENT_ID) END) VIRTUAL,
    JOB_CH_IDEMPOTENCYMERE VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN JOB_N_MID IS NULL THEN JOB_CH_IDEMPOTENCY_KEY END) VIRTUAL,
    UNIQUE KEY JOB_U_MERE (JOB_CH_MERE),
    UNIQUE KEY JOB_U_IDEMPOTENCY (JOB_CH_DEPLOYMENTMERE, JOB_CH_IDEMPOTENCYMERE),
    KEY JOB_I_QUEUE (JOB_CH_STATUS, JOB_DT_EXPIRES_AT, JOB_DT_CREATION),
    KEY JOB_I_IDEMPOTENCY (JOB_CH_DEPLOYMENT_ID, JOB_CH_IDEMPOTENCY_KEY),
    CONSTRAINT JOB_F_PARENT FOREIGN KEY (JOB_N_MID) REFERENCES T_JOB (JOB_N_ID),
    CONSTRAINT JOB_F_DEPLOYMENT FOREIGN KEY (JOB_CH_DEPLOYMENT_ID) REFERENCES T_DEPLOYMENT (DEP_CH_MERE),
    CONSTRAINT JOB_F_ACTION FOREIGN KEY (JOB_CH_ACTION_ID,JOB_N_ACTION_REVISION) REFERENCES T_ACTIONTEMPLATE (ACT_CH_MERE,ACT_N_REVISIONMERE),
    CONSTRAINT JOB_F_POLICY FOREIGN KEY (JOB_CH_POLICY_REVISION_ID) REFERENCES T_POLICYREVISION (POL_CH_MERE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

