CREATE TABLE IF NOT EXISTS T_PROJECTPROVISIONING (
    PPR_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PPR_N_MID BIGINT UNSIGNED NULL,
    PPR_CH_PROJECT_ID VARCHAR(64) NOT NULL,
    PPR_CH_DESCRIPTION VARCHAR(255) NOT NULL,
    PPR_CH_REPOSITORY VARCHAR(141) NOT NULL,
    PPR_CH_REPOSITORY_MODE VARCHAR(8) NOT NULL,
    PPR_CH_STATE VARCHAR(32) NOT NULL,
    PPR_BL_REPOSITORY_CONFIRMED TINYINT(1) NOT NULL DEFAULT 0,
    PPR_CH_MACHINE VARCHAR(128) NULL,
    PPR_CH_WORKSPACE_PATH VARCHAR(1024) NULL,
    PPR_BL_ACTIONS_ENABLED TINYINT(1) NOT NULL DEFAULT 0,
    PPR_N_REVISION BIGINT UNSIGNED NOT NULL DEFAULT 1,
    PPR_DT_CREATION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PPR_CH_CREATION VARCHAR(191) NULL,
    PPR_DT_MAJ TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PPR_DT_SUPPRESSION DATETIME(6) NULL,
    PPR_CH_SUPPRESSION VARCHAR(191) NULL,
    PPR_CH_PROJECTMERE VARCHAR(64)
        GENERATED ALWAYS AS (CASE WHEN PPR_N_MID IS NULL THEN PPR_CH_PROJECT_ID END) VIRTUAL,
    PPR_CH_REPOSITORYMERE VARCHAR(141)
        GENERATED ALWAYS AS (CASE WHEN PPR_N_MID IS NULL THEN PPR_CH_REPOSITORY END) VIRTUAL,
    UNIQUE KEY PPR_U_PROJECTMERE (PPR_CH_PROJECTMERE),
    UNIQUE KEY PPR_U_REPOSITORYMERE (PPR_CH_REPOSITORYMERE),
    CONSTRAINT PPR_F_PARENT FOREIGN KEY (PPR_N_MID) REFERENCES T_PROJECTPROVISIONING (PPR_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
