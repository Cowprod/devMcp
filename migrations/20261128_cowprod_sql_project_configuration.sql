CREATE TABLE IF NOT EXISTS T_LOCALPROJECTCONFIG (
    LPC_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    LPC_N_MID BIGINT UNSIGNED NULL,
    LPC_CH_PROJECT VARCHAR(64) NOT NULL,
    LPC_CH_CONFIG LONGTEXT NULL CHECK (JSON_VALID(LPC_CH_CONFIG)),
    LPC_DT_UPDATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    LPC_DT_CREATION DATETIME(6) NULL,
    LPC_CH_CREATION VARCHAR(191) NULL,
    LPC_DT_SUPPRESSION DATETIME(6) NULL,
    LPC_CH_SUPPRESSION VARCHAR(191) NULL,
    LPC_CH_ACTIF VARCHAR(64) GENERATED ALWAYS AS
        (CASE WHEN LPC_DT_SUPPRESSION IS NULL THEN LPC_CH_PROJECT END) VIRTUAL,
    UNIQUE KEY LPC_U_ACTIF (LPC_CH_ACTIF),
    CONSTRAINT LPC_F_PARENT FOREIGN KEY (LPC_N_MID) REFERENCES T_LOCALPROJECTCONFIG (LPC_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS T_SHAREDACTIONCONFIG (
    SAC_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    SAC_N_MID BIGINT UNSIGNED NULL,
    SAC_CH_ACTION VARCHAR(128) NOT NULL,
    SAC_CH_CONFIG LONGTEXT NULL CHECK (JSON_VALID(SAC_CH_CONFIG)),
    SAC_DT_UPDATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    SAC_DT_CREATION DATETIME(6) NULL,
    SAC_CH_CREATION VARCHAR(191) NULL,
    SAC_DT_SUPPRESSION DATETIME(6) NULL,
    SAC_CH_SUPPRESSION VARCHAR(191) NULL,
    SAC_CH_ACTIF VARCHAR(128) GENERATED ALWAYS AS
        (CASE WHEN SAC_DT_SUPPRESSION IS NULL THEN SAC_CH_ACTION END) VIRTUAL,
    UNIQUE KEY SAC_U_ACTIF (SAC_CH_ACTIF),
    CONSTRAINT SAC_F_PARENT FOREIGN KEY (SAC_N_MID) REFERENCES T_SHAREDACTIONCONFIG (SAC_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS T_PROJECTREGISTRYSTATE (
    PRS_N_ID TINYINT UNSIGNED NOT NULL PRIMARY KEY,
    PRS_BL_READY TINYINT NOT NULL DEFAULT 0,
    PRS_DT_CREATION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRS_CH_CREATION VARCHAR(191) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
