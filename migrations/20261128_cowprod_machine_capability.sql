CREATE TABLE IF NOT EXISTS T_MACHINECAPABILITY (
    MCA_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    MCA_N_MID BIGINT UNSIGNED NULL,
    MCA_CH_MACHINE VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    MCA_BL_HOSTING TINYINT NOT NULL DEFAULT 0,
    MCA_BL_CORDOVA_ANDROID TINYINT NOT NULL DEFAULT 0,
    MCA_BL_CORDOVA_IOS TINYINT NOT NULL DEFAULT 0,
    MCA_DT_CREATION DATETIME(6) NULL,
    MCA_CH_CREATION VARCHAR(191) NULL,
    MCA_DT_SUPPRESSION DATETIME(6) NULL,
    MCA_CH_SUPPRESSION VARCHAR(191) NULL,
    MCA_CH_ACTIF VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN MCA_DT_SUPPRESSION IS NULL THEN MCA_CH_MACHINE END) VIRTUAL,
    UNIQUE KEY MCA_U_ACTIF (MCA_CH_ACTIF),
    CONSTRAINT MCA_F_PARENT FOREIGN KEY (MCA_N_MID) REFERENCES T_MACHINECAPABILITY (MCA_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
