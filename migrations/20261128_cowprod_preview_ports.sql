CREATE TABLE IF NOT EXISTS T_PREVIEWPORTRESERVATION (
    PVR_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PVR_N_MID BIGINT UNSIGNED NULL,
    PVR_CH_PROJECT VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PVR_CH_MACHINE VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    PVR_N_PORT SMALLINT UNSIGNED NULL,
    PVR_DT_CREATION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PVR_CH_CREATION VARCHAR(191) NULL,
    PVR_DT_SUPPRESSION DATETIME(6) NULL,
    PVR_CH_SUPPRESSION VARCHAR(191) NULL,
    PVR_CH_ACTIF VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PVR_DT_SUPPRESSION IS NULL THEN PVR_CH_PROJECT END) VIRTUAL,
    PVR_CH_MACHINEACTIVE VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PVR_DT_SUPPRESSION IS NULL THEN PVR_CH_MACHINE END) VIRTUAL,
    PVR_N_PORTACTIF SMALLINT UNSIGNED
        GENERATED ALWAYS AS (CASE WHEN PVR_DT_SUPPRESSION IS NULL THEN PVR_N_PORT END) VIRTUAL,
    UNIQUE KEY PVR_U_PROJET (PVR_CH_ACTIF),
    UNIQUE KEY PVR_U_MACHINEPORT (PVR_CH_MACHINEACTIVE, PVR_N_PORTACTIF),
    CONSTRAINT PVR_F_PARENT FOREIGN KEY (PVR_N_MID) REFERENCES T_PREVIEWPORTRESERVATION (PVR_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
