CREATE TABLE IF NOT EXISTS T_THEME (
    THE_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    THE_N_MID BIGINT UNSIGNED NULL,
    THE_CH_SLUG VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    THE_CH_NAME VARCHAR(120) NOT NULL,
    THE_CH_PROJECT VARCHAR(64) NOT NULL,
    THE_CH_REPOSITORY VARCHAR(255) NOT NULL,
    THE_CH_PREVIEW VARCHAR(255) NOT NULL,
    THE_BL_DEFAULT TINYINT NOT NULL,
    THE_DT_CREATION DATETIME(6) NULL,
    THE_CH_CREATION VARCHAR(191) NULL,
    THE_DT_SUPPRESSION DATETIME(6) NULL,
    THE_CH_SUPPRESSION VARCHAR(191) NULL,
    THE_CH_ACTIVE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN THE_DT_SUPPRESSION IS NULL THEN THE_CH_SLUG END) VIRTUAL,
    UNIQUE KEY THE_U_ACTIVE (THE_CH_ACTIVE),
    CONSTRAINT THE_F_PARENT FOREIGN KEY (THE_N_MID) REFERENCES T_THEME (THE_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_PROJECTTHEME (
    PTH_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PTH_N_MID BIGINT UNSIGNED NULL,
    PTH_CH_PROJECT VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PTH_N_THEME BIGINT UNSIGNED NULL,
    PTH_CH_SHA CHAR(40) NULL,
    PTH_DT_CREATION DATETIME(6) NULL,
    PTH_CH_CREATION VARCHAR(191) NULL,
    PTH_DT_SUPPRESSION DATETIME(6) NULL,
    PTH_CH_SUPPRESSION VARCHAR(191) NULL,
    PTH_CH_ACTIVE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PTH_DT_SUPPRESSION IS NULL THEN PTH_CH_PROJECT END) VIRTUAL,
    UNIQUE KEY PTH_U_ACTIVE (PTH_CH_ACTIVE),
    CONSTRAINT PTH_F_PARENT FOREIGN KEY (PTH_N_MID) REFERENCES T_PROJECTTHEME (PTH_N_ID),
    CONSTRAINT PTH_F_THEME FOREIGN KEY (PTH_N_THEME) REFERENCES T_THEME (THE_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
