CREATE TABLE IF NOT EXISTS T_RUNTIMETYPE (
    RTY_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    RTY_N_MID BIGINT UNSIGNED NULL,
    RTY_CH_CODE VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    RTY_CH_LABEL VARCHAR(80) NOT NULL,
    RTY_CH_PROTOCOL ENUM('http','tcp') NOT NULL DEFAULT 'http',
    RTY_CH_SUPERVISOR VARCHAR(24) NOT NULL DEFAULT 'systemd',
    RTY_BL_SELECTABLE TINYINT NOT NULL DEFAULT 1,
    RTY_DT_CREATION DATETIME(6) NULL,
    RTY_CH_CREATION VARCHAR(191) NULL,
    RTY_DT_SUPPRESSION DATETIME(6) NULL,
    RTY_CH_SUPPRESSION VARCHAR(191) NULL,
    RTY_CH_ACTIVE VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN RTY_DT_SUPPRESSION IS NULL THEN RTY_CH_CODE END) VIRTUAL,
    UNIQUE KEY RTY_U_ACTIVE (RTY_CH_ACTIVE),
    CONSTRAINT RTY_F_PARENT FOREIGN KEY (RTY_N_MID) REFERENCES T_RUNTIMETYPE (RTY_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS T_PROJECTRUNTIME (
    PRT_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PRT_N_MID BIGINT UNSIGNED NULL,
    PRT_CH_PROJECT VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRT_N_RUNTIMETYPE BIGINT UNSIGNED NULL,
    PRT_CH_DESIREDSTATE ENUM('stopped','running') NOT NULL DEFAULT 'stopped',
    PRT_CH_ENTRYPOINT VARCHAR(255) NULL,
    PRT_CH_DOCUMENTROOT VARCHAR(255) NULL,
    PRT_CH_HEALTHPATH VARCHAR(255) NOT NULL DEFAULT '/',
    PRT_N_REVISION INT UNSIGNED NOT NULL DEFAULT 1,
    PRT_DT_UPDATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRT_DT_CREATION DATETIME(6) NULL,
    PRT_CH_CREATION VARCHAR(191) NULL,
    PRT_DT_SUPPRESSION DATETIME(6) NULL,
    PRT_CH_SUPPRESSION VARCHAR(191) NULL,
    PRT_CH_ACTIVE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PRT_DT_SUPPRESSION IS NULL THEN PRT_CH_PROJECT END) VIRTUAL,
    UNIQUE KEY PRT_U_ACTIVE (PRT_CH_ACTIVE),
    KEY PRT_I_PROJECTREVISION (PRT_CH_PROJECT, PRT_N_REVISION),
    CONSTRAINT PRT_F_PARENT FOREIGN KEY (PRT_N_MID) REFERENCES T_PROJECTRUNTIME (PRT_N_ID),
    CONSTRAINT PRT_F_RUNTIMETYPE FOREIGN KEY (PRT_N_RUNTIMETYPE) REFERENCES T_RUNTIMETYPE (RTY_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
