CREATE TABLE IF NOT EXISTS T_MACHINE (
    MAC_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    MAC_N_MID BIGINT UNSIGNED NULL,
    MAC_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    MAC_CH_NAME VARCHAR(128) NOT NULL,
    MAC_CH_OS_FAMILY VARCHAR(32) NOT NULL,
    MAC_CH_ARCHITECTURE VARCHAR(32) NOT NULL,
    MAC_CH_AGENT_VERSION VARCHAR(64) NULL,
    MAC_CH_STATUS ENUM('pending','active','disabled','revoked') NOT NULL DEFAULT 'pending',
    MAC_DT_LAST_SEEN_AT DATETIME(6) NULL,
    MAC_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    MAC_CH_CREATION VARCHAR(191) NULL,
    MAC_DT_SUPPRESSION DATETIME(6) NULL,
    MAC_CH_SUPPRESSION VARCHAR(191) NULL,
    MAC_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN MAC_N_MID IS NULL THEN RTRIM(MAC_CH_ID) END) STORED,
    MAC_CH_NAMEMERE VARCHAR(128)
        GENERATED ALWAYS AS (CASE WHEN MAC_N_MID IS NULL THEN MAC_CH_NAME END) VIRTUAL,
    UNIQUE KEY MAC_U_MERE (MAC_CH_MERE),
    UNIQUE KEY MAC_U_NAMEMERE (MAC_CH_NAMEMERE),
    KEY MAC_I_REMOTE (MAC_CH_ID,MAC_CH_STATUS),
    CONSTRAINT MAC_F_PARENT FOREIGN KEY (MAC_N_MID) REFERENCES T_MACHINE (MAC_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_AGENTIDENTITY (
    AGI_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    AGI_N_MID BIGINT UNSIGNED NULL,
    AGI_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    AGI_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    AGI_CH_CREDENTIAL_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    AGI_DT_EXPIRES_AT DATETIME(6) NOT NULL,
    AGI_DT_REVOKED_AT DATETIME(6) NULL,
    AGI_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    AGI_CH_CREATION VARCHAR(191) NULL DEFAULT 'service:devmcp-enrollment',
    AGI_DT_SUPPRESSION DATETIME(6) NULL,
    AGI_CH_SUPPRESSION VARCHAR(191) NULL,
    AGI_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN AGI_N_MID IS NULL THEN RTRIM(AGI_CH_ID) END) VIRTUAL,
    AGI_CH_HASHMERE CHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN AGI_N_MID IS NULL THEN RTRIM(AGI_CH_CREDENTIAL_HASH) END) VIRTUAL,
    UNIQUE KEY AGI_U_MERE (AGI_CH_MERE),
    UNIQUE KEY AGI_U_HASHMERE (AGI_CH_HASHMERE),
    KEY AGI_I_CREDENTIAL (AGI_CH_CREDENTIAL_HASH, AGI_CH_MACHINE_ID, AGI_DT_REVOKED_AT),
    CONSTRAINT AGI_F_PARENT FOREIGN KEY (AGI_N_MID) REFERENCES T_AGENTIDENTITY (AGI_N_ID),
    CONSTRAINT AGI_F_MACHINE FOREIGN KEY (AGI_CH_MACHINE_ID) REFERENCES T_MACHINE (MAC_CH_MERE),
    CONSTRAINT AGI_C_HASH CHECK (AGI_N_MID IS NOT NULL OR AGI_CH_CREDENTIAL_HASH IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_ENROLLMENTINVITATION (
    ENI_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ENI_N_MID BIGINT UNSIGNED NULL,
    ENI_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ENI_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ENI_CH_TOKEN_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    ENI_DT_EXPIRES_AT DATETIME(6) NOT NULL,
    ENI_DT_CONSUMED_AT DATETIME(6) NULL,
    ENI_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    ENI_CH_CREATION VARCHAR(191) NULL DEFAULT 'service:devmcp-enrollment',
    ENI_DT_SUPPRESSION DATETIME(6) NULL,
    ENI_CH_SUPPRESSION VARCHAR(191) NULL,
    ENI_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN ENI_N_MID IS NULL THEN RTRIM(ENI_CH_ID) END) VIRTUAL,
    ENI_CH_HASHMERE CHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN ENI_N_MID IS NULL THEN RTRIM(ENI_CH_TOKEN_HASH) END) VIRTUAL,
    UNIQUE KEY ENI_U_MERE (ENI_CH_MERE),
    UNIQUE KEY ENI_U_HASHMERE (ENI_CH_HASHMERE),
    KEY ENI_I_TOKEN (ENI_CH_TOKEN_HASH, ENI_DT_CONSUMED_AT),
    KEY ENI_I_MACHINE (ENI_CH_MACHINE_ID, ENI_DT_CONSUMED_AT),
    CONSTRAINT ENI_F_PARENT FOREIGN KEY (ENI_N_MID) REFERENCES T_ENROLLMENTINVITATION (ENI_N_ID),
    CONSTRAINT ENI_F_MACHINE FOREIGN KEY (ENI_CH_MACHINE_ID) REFERENCES T_MACHINE (MAC_CH_MERE),
    CONSTRAINT ENI_C_HASH CHECK (ENI_N_MID IS NOT NULL OR ENI_CH_TOKEN_HASH IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
