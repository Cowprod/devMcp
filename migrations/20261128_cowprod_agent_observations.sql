CREATE TABLE IF NOT EXISTS T_AGENTZEROTIERADDRESS (
    AZA_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    AZA_N_MID BIGINT UNSIGNED NULL,
    AZA_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    AZA_CH_IPV4 VARCHAR(15) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    AZA_DT_OBSERVED_AT DATETIME(6) NOT NULL,
    AZA_DT_CREATION DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
    AZA_CH_CREATION VARCHAR(191) NULL,
    AZA_DT_SUPPRESSION DATETIME(6) NULL,
    AZA_CH_SUPPRESSION VARCHAR(191) NULL,
    AZA_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN AZA_N_MID IS NULL THEN RTRIM(AZA_CH_MACHINE_ID) END) VIRTUAL,
    UNIQUE KEY AZA_U_MERE (AZA_CH_MERE),
    CONSTRAINT AZA_F_PARENT FOREIGN KEY (AZA_N_MID) REFERENCES T_AGENTZEROTIERADDRESS (AZA_N_ID),
    CONSTRAINT AZA_F_MACHINE FOREIGN KEY (AZA_CH_MACHINE_ID) REFERENCES dm_machine (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS T_WORKSPACEDIAGNOSTIC (
    WDG_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    WDG_N_MID BIGINT UNSIGNED NULL,
    WDG_CH_DEPLOYMENT_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    WDG_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    WDG_CH_STATUS ENUM('present','missing','invalid','not_git') NOT NULL,
    WDG_CH_BRANCH VARCHAR(200) NULL,
    WDG_CH_COMMIT_SHA CHAR(40) CHARACTER SET ascii COLLATE ascii_bin NULL,
    WDG_DT_INSPECTED_AT DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    WDG_DT_CREATION DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
    WDG_CH_CREATION VARCHAR(191) NULL,
    WDG_DT_SUPPRESSION DATETIME(6) NULL,
    WDG_CH_SUPPRESSION VARCHAR(191) NULL,
    WDG_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN WDG_N_MID IS NULL THEN RTRIM(WDG_CH_DEPLOYMENT_ID) END) VIRTUAL,
    UNIQUE KEY WDG_U_MERE (WDG_CH_MERE),
    CONSTRAINT WDG_F_PARENT FOREIGN KEY (WDG_N_MID) REFERENCES T_WORKSPACEDIAGNOSTIC (WDG_N_ID),
    CONSTRAINT WDG_F_DEPLOYMENT FOREIGN KEY (WDG_CH_DEPLOYMENT_ID) REFERENCES T_DEPLOYMENT (DEP_CH_MERE),
    CONSTRAINT WDG_F_MACHINE FOREIGN KEY (WDG_CH_MACHINE_ID) REFERENCES dm_machine (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
