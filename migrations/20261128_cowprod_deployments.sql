CREATE TABLE IF NOT EXISTS T_DEPLOYMENT (
    DEP_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    DEP_N_MID BIGINT UNSIGNED NULL,
    DEP_CH_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    DEP_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    DEP_CH_PROJECT_ID VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    DEP_CH_WORKSPACE_PATH VARCHAR(2048) NULL,
    DEP_BL_ENABLED TINYINT NOT NULL DEFAULT 0,
    DEP_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    DEP_CH_CREATION VARCHAR(191) NULL,
    DEP_DT_SUPPRESSION DATETIME(6) NULL,
    DEP_CH_SUPPRESSION VARCHAR(191) NULL,
    DEP_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN DEP_N_MID IS NULL THEN RTRIM(DEP_CH_ID) END) STORED,
    DEP_CH_MACHINEMERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN DEP_N_MID IS NULL THEN RTRIM(DEP_CH_MACHINE_ID) END) VIRTUAL,
    DEP_CH_PROJECTMERE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN DEP_N_MID IS NULL THEN DEP_CH_PROJECT_ID END) VIRTUAL,
    UNIQUE KEY DEP_U_MERE (DEP_CH_MERE),
    UNIQUE KEY DEP_U_MACHINEPROJET (DEP_CH_MACHINEMERE, DEP_CH_PROJECTMERE),
    CONSTRAINT DEP_F_PARENT FOREIGN KEY (DEP_N_MID) REFERENCES T_DEPLOYMENT (DEP_N_ID),
    CONSTRAINT DEP_F_MACHINE FOREIGN KEY (DEP_CH_MACHINE_ID) REFERENCES dm_machine (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
