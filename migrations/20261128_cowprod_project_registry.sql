CREATE TABLE IF NOT EXISTS T_PROJECT (
    PRO_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PRO_N_MID BIGINT UNSIGNED NULL,
    PRO_CH_SLUG VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PRO_CH_DESCRIPTION VARCHAR(255) NOT NULL DEFAULT '',
    PRO_CH_REPOSITORY VARCHAR(1024) NULL,
    PRO_DT_CREATION DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRO_CH_CREATION VARCHAR(191) NULL,
    PRO_DT_SUPPRESSION DATETIME(6) NULL,
    PRO_CH_SUPPRESSION VARCHAR(191) NULL,
    PRO_CH_MERE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PRO_N_MID IS NULL THEN PRO_CH_SLUG END) VIRTUAL,
    PRO_CH_ACTIF VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PRO_N_MID IS NULL AND PRO_DT_SUPPRESSION IS NULL THEN PRO_CH_SLUG END) STORED,
    UNIQUE KEY PRO_U_MERE (PRO_CH_MERE),
    UNIQUE KEY PRO_U_ACTIF (PRO_CH_ACTIF),
    CONSTRAINT PRO_F_PARENT FOREIGN KEY (PRO_N_MID) REFERENCES T_PROJECT (PRO_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
