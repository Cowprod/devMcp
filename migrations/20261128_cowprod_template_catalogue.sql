CREATE TABLE IF NOT EXISTS T_TEMPLATE (
    TPL_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    TPL_N_MID BIGINT UNSIGNED NULL,
    TPL_CH_SLUG VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    TPL_CH_NAME VARCHAR(120) NOT NULL,
    TPL_CH_TYPE VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    TPL_CH_PROJECT VARCHAR(64) NOT NULL,
    TPL_CH_REPOSITORY VARCHAR(255) NOT NULL,
    TPL_BL_DEFAULT TINYINT NOT NULL,
    TPL_DT_CREATION DATETIME(6) NULL,
    TPL_CH_CREATION VARCHAR(191) NULL,
    TPL_DT_SUPPRESSION DATETIME(6) NULL,
    TPL_CH_SUPPRESSION VARCHAR(191) NULL,
    TPL_CH_ACTIVE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN TPL_DT_SUPPRESSION IS NULL THEN TPL_CH_SLUG END) VIRTUAL,
    UNIQUE KEY TPL_U_ACTIVE (TPL_CH_ACTIVE),
    CONSTRAINT TPL_F_PARENT FOREIGN KEY (TPL_N_MID) REFERENCES T_TEMPLATE (TPL_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS T_PROJECTTEMPLATE (
    PTP_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    PTP_N_MID BIGINT UNSIGNED NULL,
    PTP_CH_PROJECT VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    PTP_N_TEMPLATE BIGINT UNSIGNED NULL,
    PTP_CH_SOURCE CHAR(40) NULL,
    PTP_CH_APPLIED CHAR(40) NULL,
    PTP_DT_CREATION DATETIME(6) NULL,
    PTP_CH_CREATION VARCHAR(191) NULL,
    PTP_DT_SUPPRESSION DATETIME(6) NULL,
    PTP_CH_SUPPRESSION VARCHAR(191) NULL,
    PTP_CH_ACTIVE VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN PTP_DT_SUPPRESSION IS NULL THEN PTP_CH_PROJECT END) VIRTUAL,
    UNIQUE KEY PTP_U_ACTIVE (PTP_CH_ACTIVE),
    CONSTRAINT PTP_F_PARENT FOREIGN KEY (PTP_N_MID) REFERENCES T_PROJECTTEMPLATE (PTP_N_ID),
    CONSTRAINT PTP_F_TEMPLATE FOREIGN KEY (PTP_N_TEMPLATE) REFERENCES T_TEMPLATE (TPL_N_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
