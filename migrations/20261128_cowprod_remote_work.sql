CREATE TABLE IF NOT EXISTS T_REMOTEPROJECT (
    RPR_N_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    RPR_N_MID BIGINT UNSIGNED NULL,
    RPR_CH_PROJECT_ID VARCHAR(64) NOT NULL,
    RPR_CH_DEPLOYMENT_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    RPR_CH_MACHINE_ID CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    RPR_CH_REPOSITORY VARCHAR(141) NOT NULL,
    RPR_CH_WORKSPACE_PATH VARCHAR(1024) NOT NULL,
    RPR_CH_CONFIG_JSON MEDIUMTEXT NULL,
    RPR_N_CONFIG_REVISION INT UNSIGNED NOT NULL DEFAULT 1,
    RPR_BL_READY TINYINT(1) NOT NULL DEFAULT 0,
    RPR_CH_METADATA_JSON MEDIUMTEXT NULL,
    RPR_DT_CREATION DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6),
    RPR_CH_CREATION VARCHAR(191) NULL DEFAULT 'service:devmcp-remote',
    RPR_DT_SUPPRESSION DATETIME(6) NULL,
    RPR_CH_SUPPRESSION VARCHAR(191) NULL,
    RPR_CH_MERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN RPR_N_MID IS NULL THEN RTRIM(RPR_CH_DEPLOYMENT_ID) END) VIRTUAL,
    RPR_CH_PROJECTMERE VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN RPR_N_MID IS NULL THEN RPR_CH_PROJECT_ID END) VIRTUAL,
    RPR_CH_MACHINEMERE CHAR(32) CHARACTER SET ascii COLLATE ascii_bin
        GENERATED ALWAYS AS (CASE WHEN RPR_N_MID IS NULL THEN RTRIM(RPR_CH_MACHINE_ID) END) VIRTUAL,
    UNIQUE KEY RPR_U_PROJECTMACHINE (RPR_CH_PROJECTMERE,RPR_CH_MACHINEMERE),
    KEY RPR_I_PROJECT (RPR_CH_PROJECT_ID,RPR_CH_MACHINE_ID),
    UNIQUE KEY RPR_U_MERE (RPR_CH_MERE),
    CONSTRAINT RPR_F_PARENT FOREIGN KEY (RPR_N_MID) REFERENCES T_REMOTEPROJECT (RPR_N_ID),
    CONSTRAINT RPR_F_MACHINE FOREIGN KEY (RPR_CH_MACHINE_ID) REFERENCES dm_machine (id),
    CONSTRAINT RPR_F_DEPLOYMENT FOREIGN KEY (RPR_CH_DEPLOYMENT_ID) REFERENCES T_DEPLOYMENT (DEP_CH_MERE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

